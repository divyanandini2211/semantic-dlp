# ── Audit Log (SQLite) ────────────────────────────────────────────────────────
DB_PATH = str(config.AUDIT_DB_PATH)

def _get_db() -> sqlite3.Connection:
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn

def _init_db() -> None:
    conn = _get_db()
    cols = {row[1] for row in conn.execute("PRAGMA table_info(audit_logs)").fetchall()}
    if cols and "id" not in cols:
        conn.execute("ALTER TABLE audit_logs RENAME TO audit_logs_legacy")
        cols = set()
    if not cols:
        conn.execute(
            """CREATE TABLE IF NOT EXISTS audit_logs (
                id        INTEGER PRIMARY KEY AUTOINCREMENT,
                timestamp DATETIME DEFAULT CURRENT_TIMESTAMP,
                agent_id  TEXT,
                decision  TEXT,
                details   TEXT
            )"""
        )
    conn.commit()
    conn.close()

def _log_decision(agent_id: str, decision: str, details: dict) -> None:
    conn = _get_db()
    conn.execute(
        "INSERT INTO audit_logs (agent_id, decision, details) VALUES (?, ?, ?)",
        (agent_id, decision, json.dumps(details)),
    )
    conn.commit()
    conn.close()

_init_db()


# ── Request / Response Schemas ────────────────────────────────────────────────

class InspectRequest(BaseModel):
    agent_id: str = Field(..., description="ID of the AI agent generating the output")
    output_text: str = Field(..., description="Agent-generated text to inspect")

class InspectResponse(BaseModel):
    decision: str
    details: dict[str, Any]

class AgentChatRequest(BaseModel):
    agent_id: Optional[str] = Field("enterprise-assistant-01", description="Identifier for the agent instance")
    message: str = Field(..., description="User prompt or malicious query sent to the Enterprise Agent")

class AgentChatResponse(BaseModel):
    message: str = Field(..., description="Filtered message displayed in chat (actual response if ALLOW, or blocked alert)")
    raw_agent_output: str = Field(..., description="Draft response generated by LLM 1 prior to guardrail filtering")
    decision: str = Field(..., description="DLP guardrail decision: ALLOW or BLOCK")
    dlp_inspection: dict[str, Any] = Field(..., description="Full multi-stage pipeline trace and similarity scores")


