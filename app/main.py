@app.get("/api/v1/audit/logs", tags=["Audit"])
def get_audit_logs(
    limit: int = Query(50, ge=1, le=500, description="Number of most recent entries to return"),
    decision: str = Query(None, description="Filter by decision: ALLOW | BLOCK | ERROR"),
):
    """Return recent audit log entries from SQLite."""
    conn = _get_db()
    if decision:
        rows = conn.execute(
            "SELECT * FROM audit_logs WHERE decision = ? ORDER BY id DESC LIMIT ?",
            (decision.upper(), limit),
        ).fetchall()
    else:
        rows = conn.execute(
            "SELECT * FROM audit_logs ORDER BY id DESC LIMIT ?",
            (limit,),
        ).fetchall()
    conn.close()

    entries = []
    for row in rows:
        entry = dict(row)
        try:
            raw_det = entry.get("details")
            details = json.loads(raw_det) if isinstance(raw_det, str) else (raw_det or {})
            entry["details"] = details
            insp = details.get("inspection", {}) if isinstance(details, dict) else {}
            entry["lineage_tag"] = insp.get("lineage_tag") or details.get("lineage_tag") or "-"
            entry["similarity_score"] = float(insp.get("similarity_score", 0.0)) if insp else float(details.get("similarity_score", 0.0))
            entry["reason"] = insp.get("reason") or details.get("reason") or ""
        except Exception:
            pass
        entries.append(entry)

    return {"total": len(entries), "entries": entries}


@app.delete("/api/v1/audit/logs", tags=["Audit"])
def clear_audit_logs():
    """Clear all audit log entries."""
    conn = _get_db()
    conn.execute("DELETE FROM audit_logs")
    conn.commit()
    conn.close()
    logger.warning("Audit log cleared.")
    return {"status": "cleared", "message": "All audit log entries deleted."}


