@app.post("/api/v1/agent/chat", response_model=AgentChatResponse, tags=["Enterprise Chat"])
def agent_chat_endpoint(payload: AgentChatRequest):
    """
    Full End-to-End Chat Flow:
    1. User prompt sent to LLM 1 (Enterprise Agent with Pinecone RAG context).
    2. LLM 1 generates a draft response.
    3. Aegis DLP intercepts the draft before delivering it.
    4. Evaluates via Regex -> Pinecone Vector Distance -> LLM 2 (DLP Auditor).
    5. Returns safe message to user + complete real-time inspection trace.
    """
    logger.info("Chat request for agent_id=%s — Query: %s", payload.agent_id, payload.message[:60])
    
    # Step 1: Generate response from LLM 1 (Enterprise Agent)
    agent_gen = generate_enterprise_agent_response(payload.message)
    raw_output = agent_gen.get("raw_response", "")
    
    # Step 2: Pass through Aegis DLP Guardrail (Stage 1 -> Stage 2 -> LLM 2 Auditor)
    inspection_result = inspect_agent_output(raw_output)
    decision = inspection_result.get("decision", "ALLOW")
    
    # Log to audit database
    _log_decision(payload.agent_id, decision, {
        "user_query": payload.message,
        "raw_agent_output": raw_output,
        "inspection": inspection_result
    })
    
    # Step 3: Format safe user-facing message
    if decision == "BLOCK":
        lineage = inspection_result.get("lineage_tag", "PROTECTED_RECORD")
        user_message = f"[OUTPUT BLOCKED: Sensitive data exfiltration detected. Source Lineage: {lineage}]"
    elif decision == "ERROR":
        user_message = f"[SYSTEM ERROR: Guardrail evaluation failed. Traffic held fail-closed.]"
    else:
        user_message = raw_output
        
    return AgentChatResponse(
        message=user_message,
        raw_agent_output=raw_output,
        decision=decision,
        dlp_inspection=inspection_result,
    )


@app.post("/api/v1/inspect", response_model=InspectResponse, tags=["Detection"])
def inspect_endpoint(payload: InspectRequest):
    """
    Direct DLP Inspection Endpoint:
    Inspect arbitrary agent output text for semantic exfiltration of protected facts.
    """
    logger.info("Direct inspect request — agent_id=%s", payload.agent_id)
    result = inspect_agent_output(payload.output_text)
    decision = result.get("decision", "ERROR")
    logger.info("Decision: %s — agent_id=%s", decision, payload.agent_id)
    _log_decision(payload.agent_id, decision, result)
    return InspectResponse(decision=decision, details=result)


@app.get("/api/v1/vault/status", tags=["Vault"])
def vault_status():
    """Return live stats from the Pinecone Cloud vector index."""
    try:
        from pinecone import Pinecone
        pc = Pinecone(api_key=config.PINECONE_API_KEY)
        idx = pc.Index(config.PINECONE_INDEX_NAME)
        stats = idx.describe_index_stats()
        return {
            "index_name": config.PINECONE_INDEX_NAME,
            "total_vectors": stats.get("total_vector_count", 0),
            "dimension": stats.get("dimension", 0),
            "namespaces": stats.get("namespaces", {}),
        }
    except Exception as exc:
        raise HTTPException(status_code=503, detail=f"Vault unavailable: {exc}")


